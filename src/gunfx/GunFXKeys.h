	// The settings section of a GunFX.ini section: "Main.GunFX.<section>", [Main] = "Main.GunFX.General".
	inline void TomlSection(const char* ini, char* out, unsigned size) {
		strcpy_s(out, size, "Main.GunFX.");
		strcat_s(out, size, _stricmp(ini, "Main") ? ini : "General");
	}
	// The settings key of a GunFX.ini key: without its type letter (fScale -> Scale), except [Volume] bPlayerPush -> PlayerPushOn
	// (fPlayerPush is a key of its own).
	inline const char* TomlKey(const char* section, const char* ini) {
		if (!_stricmp(section, "Volume") && !_stricmp(ini, "bPlayerPush")) return "PlayerPushOn";
		return ini[0] ? ini + 1 : ini;
	}
	// An effect's GunFX.ini bEnabled is its menu switch instead ([Main.GunFX.Main]); nullptr for any other key.
	inline const char* SwitchOf(const char* section, const char* ini) {
		if (_stricmp(ini, "bEnabled")) return nullptr;
		static const char* const map[][2] = { { "Puff", "Puff" }, { "Wisp", "HeatSmoke" }, { "Trail", "AfterFireTrail" }, { "Volume", "VolumetricSmoke" },
			{ "Ejection", "EjectionSmoke" }, { "Glow", "BarrelGlow" }, { "Haze", "HeatHaze" }, { "Blast", "MuzzleBlast" } };
		for (const auto& m : map) if (!_stricmp(section, m[0])) return m[1];
		return nullptr;
	}
